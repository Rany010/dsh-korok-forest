/**
 * Build the override layer accepted by ctx.theme.overrideTokens.
 * @returns {Record<string, {light: string, dark: string}>}
 */
export function themeOverrides() {
  /** @type {Record<string, {light: string, dark: string}>} */
  const overrides = {}
  for (const [semantic, cssName] of TOKEN_MAP) {
    const lightValue = LIGHT[semantic]
    const darkValue = DARK[semantic]
    if (typeof lightValue !== 'string' || typeof darkValue !== 'string') {
      throw new Error(`Missing Korok semantic color: ${semantic}`)
    }
    overrides[cssName] = { light: lightValue, dark: darkValue }
  }
  return overrides
}
